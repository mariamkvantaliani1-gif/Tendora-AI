# სესიის დავალებების საცავი (თითო thread_id-ზე ცალკე)
# შეგიძლია ასევე tool-ებში გადასცე config: RunnableConfig და გამოიყენო config["configurable"]["thread_id"]
TASKS_STORE: dict[str, list[dict[str, Any]]] = {}

DEFAULT_THREAD_ID = "demo-creator-1"


def _get_thread_tasks(thread_id: str = DEFAULT_THREAD_ID) -> list[dict[str, Any]]:
    return TASKS_STORE.setdefault(thread_id, [])


@tool
def add_task(title: str, thread_id: str = DEFAULT_THREAD_ID) -> str:
    """ამატებს ახალ დავალებას კონტენტ-კრეატორის სიაში."""
    tasks = _get_thread_tasks(thread_id)
    new_task = {
        "id": len(tasks) + 1,
        "title": title.strip(),
        "done": False,
    }
    tasks.append(new_task)
    return f"დავალება დაემატა: #{new_task['id']} — {new_task['title']}"


@tool
def list_tasks(thread_id: str = DEFAULT_THREAD_ID) -> str:
    """აბრუნებს მიმდინარე დავალებების სიას."""
    tasks = _get_thread_tasks(thread_id)
    if not tasks:
        return "დავალებების სია ცარიელია."
    lines = [
        f"#{t['id']}. {t['title']} ({'შესრულებული' if t['done'] else 'აქტიური'})"
        for t in tasks
    ]
    return "თქვენი დავალებები:\n" + "\n".join(lines)


@tool
def delete_task(task_query: str, thread_id: str = DEFAULT_THREAD_ID) -> str:
    """შლის დავალებას ID-ით ან სათაურით — წაშლამდე ითხოვს დადასტურებას interrupt()-ით."""
    tasks = _get_thread_tasks(thread_id)
    query_clean = task_query.strip().lower()

    # ვპოულობთ ზუსტ დავალებას წაშლამდე
    matched_task = None
    for t in tasks:
        if str(t["id"]) == query_clean or query_clean in t["title"].lower():
            matched_task = t
            break

    if matched_task is None:
        return f"დავალება '{task_query}' სიაში ვერ მოიძებნა."

    # ვაჩერებთ აგენტს და ვაჩვენებთ ზუსტად რის წაშლას ვაპირებთ
    approved = interrupt({
        "action": "delete_task",
        "task_id": matched_task["id"],
        "task_title": matched_task["title"],
        "message": f"დაადასტურეთ დავალების წაშლა: #{matched_task['id']} — '{matched_task['title']}'?"
    })

    # რეალური წაშლა მხოლოდ interrupt()-ის შემდეგ, resume=True-ზე
    if approved is True:
        TASKS_STORE[thread_id] = [t for t in tasks if t["id"] != matched_task["id"]]
        return f"დავალება #{matched_task['id']} ('{matched_task['title']}') წაიშალა."

    # resume=False-ზე მონაცემი უცვლელი რჩება
    return f"წაშლა გაუქმდა. დავალება #{matched_task['id']} ('{matched_task['title']}') უცვლელი დარჩა."

